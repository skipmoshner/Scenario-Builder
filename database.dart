class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  @override
  int get schemaVersion => 1;

  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (Migrator m) async {
          await m.createAll();
          await _seedDefaultSchedulerRoles();
        },
      );

  Future<void> _seedDefaultSchedulerRoles() async {
    // "Applicant (Self)" is system-protected — core scheduling logic
    // depends on this row existing. The other two ship as editable
    // defaults per the confirmed decisions log.
    await into(schedulerRoles).insert(
      SchedulerRolesCompanion.insert(
        roleName: 'Applicant (Self)',
        isSystemDefault: const Value(true),
      ),
    );
    await into(schedulerRoles).insert(
      SchedulerRolesCompanion.insert(
        roleName: 'Recommending Instructor',
        isSystemDefault: const Value(false),
      ),
    );
    await into(schedulerRoles).insert(
      SchedulerRolesCompanion.insert(
        roleName: 'Student Coordinator',
        isSystemDefault: const Value(false),
      ),
    );
  }
}

/// Opens the local database. [passphrase] is currently unused (see the
/// TEMPORARY note above) — kept as a parameter so callers don't need to
/// change once encryption is restored.
LazyDatabase openConnection(String passphrase) {
  return LazyDatabase(() async {
    final dbFolder = await getApplicationDocumentsDirectory();
    final file = File(p.join(dbFolder.path, 'dpe_toolkit.sqlite'));
    return NativeDatabase.createInBackground(file);
  });
}
