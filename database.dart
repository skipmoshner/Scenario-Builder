// TEMPORARY — NOT ENCRYPTED. SQLCipher (whole-database encryption) was
// removed for local Windows development because sqlcipher_flutter_libs
// requires a separate OpenSSL install + OPENSSL_ROOT_DIR environment
// variable to build, which broke the Windows CMake build on first run.
//
// Before this app handles real applicant PII, restore encryption:
//   1. Install OpenSSL for Windows (the Win64 installer from
//      https://slproweb.com/products/Win32OpenSSL.html works)
//   2. Set OPENSSL_ROOT_DIR to wherever it installs (e.g. C:\Program
//      Files\OpenSSL-Win64)
//   3. Add sqlcipher_flutter_libs back to pubspec.yaml
//   4. Swap the imports/openConnection body below back to the
//      SQLCipher version (open.overrideFor + the PRAGMA key line)
//   5. Also still needed regardless: pull the passphrase from secure
//      per-device storage (flutter_secure_storage or platform keychain)
//      instead of a hardcoded string — see openConnection() below.

